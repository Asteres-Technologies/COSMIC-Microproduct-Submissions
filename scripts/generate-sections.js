const fs = require('fs');
const path = require('path');

// Path to sections directory
const sectionsDir = path.join(process.cwd(), 'content', 'sections');
const outputFile = path.join(process.cwd(), 'lib', 'sections-loader.ts');

// Read all section files
const files = fs.readdirSync(sectionsDir);

// Filter and sort section files (only .ts files with number prefix)
const sectionFiles = files
  .filter(file => file.endsWith('.ts') && file.match(/^\d{2}-/))
  .sort();

// Generate import statements
const imports = sectionFiles.map((file, index) => {
  const fileName = file.replace('.ts', '');
  return `import { section as section${String(index + 1).padStart(2, '0')} } from '@/content/sections/${fileName}';`;
}).join('\n');

// Generate sections array
const sectionVars = sectionFiles.map((file, index) => {
  return `section${String(index + 1).padStart(2, '0')}`;
}).join(', ');

// Generate the complete file content
const fileContent = `// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// This file is generated by scripts/generate-sections.js
// Run 'npm run generate-sections' to regenerate

${imports}

export const sections = [${sectionVars}];
`;

// Write the generated file
fs.writeFileSync(outputFile, fileContent, 'utf8');

console.log(`✅ Generated sections loader with ${sectionFiles.length} sections`);
console.log(`   Output: ${outputFile}`);
